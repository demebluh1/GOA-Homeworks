#N1
# Boolean არის მონაცემთა ტიპი, რომელიც გამოიყენება ჭეშმარიტებისა (True) და ცრუობის (False) მნიშვნელობების გამოსახატად.
# მას აქვს მხოლოდ ორი შესაძლო მნიშვნელობა: True (მართალია) და False (მცდარია).

# მაგალითად:
x = True   # ეს ნიშნავს რომ x-ის მნიშვნელობა არის მართალი
y = False  # ეს ნიშნავს რომ y-ის მნიშვნელობა არის მცდარი

# Boolean ტიპის მნიშვნელობა ხშირად მიიღება შედარების შედეგად:
a = 5
b = 3

print(a > b)  # დაბრუნდება True, რადგან 5 მართლაც მეტია 3-ზე
print(a < b)  # დაბრუნდება False, რადგან 5 ნაკლები არ არის 3-ზე


#N2
# Binary code (ბინარული კოდი) — ეს არის სისტემა, რომლის მეშვეობითაც კომპიუტერი ინახავს და ამუშავებს მონაცემებს მხოლოდ ორი ციფრით: 0 და 1.
# ბინარული სისტემა არის ორბითი, რაც ნიშნავს, რომ მასში მხოლოდ ორი მნიშვნელობა არსებობს.

# კომპიუტერი ვერ ესმის ასოები ან რიცხვები ისე, როგორც ადამიანი — მას ყველაფერი გადაჰყავს ბინარულ კოდში.

# 1 ნიშნავს "მიმართულია ელექტრული სიგნალი" (არის დენი)
# 0 ნიშნავს "არ არის ელექტრული სიგნალი" (არ არის დენი)

# მაგალითად:
# ასო "A" ბინარულად იწერება როგორც 01000001
# რიცხვი 5 ბინარულად იწერება როგორც 101

# კომპიუტერი ამ 0-ებსა და 1-ებს კითხულობს და მათგან ქმნის ტექსტს, გამოსახულებებს, ხმას და სხვა ყველაფერს.

# შემაჯამებლად:
# 0 = გამორთული სიგნალი (False)
# 1 = ჩართული სიგნალი (True)


#N3
# bool() არის ჩაშენებული (built-in) ფუნქცია Python-ში, რომელიც ნებისმიერი მნიშვნელობა გარდაქმნის Boolean ტიპად.
# მისი მიზანია შეამოწმოს — „მართალია“ თუ „მცდარია“ მოცემული მნიშვნელობა.

# შედეგი ყოველთვის იქნება True ან False.

# მაგალითები:
print(bool(5))       # True, რადგან 5 არის რიცხვი და არ არის 0
print(bool(0))       # False, რადგან 0 ითვლება ცრუ მნიშვნელობად
print(bool("Hello")) # True, რადგან სტრინგი ცარიელი არ არის
print(bool(""))      # False, რადგან ცარიელი სტრინგი ითვლება მცდარად
print(bool([]))      # False, ცარიელი სია არის False
print(bool([1, 2]))  # True, რადგან სიაში ელემენტები არსებობს

# შემაჯამებლად:
# bool() აბრუნებს True — როცა მნიშვნელობა არსებობს ან არ არის ცარიელი
# bool() აბრუნებს False — როცა მნიშვნელობა ცარიელია, ნულია ან არ არსებობს


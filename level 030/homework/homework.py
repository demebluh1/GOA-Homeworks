#N1
# .upper() — სტრინგის ყველა ასოს გადააქცევს დიდ ასოდ
text = "hello"
print(text.upper())  # შედეგი: "HELLO"


# .lower() — სტრინგის ყველა ასოს გადააქცევს პატარა ასოდ
text = "HELLO"
print(text.lower())  # შედეგი: "hello"


# .capitalize() — სტრინგის მხოლოდ პირველ ასოს გადააქცევს დიდ ასოდ,
# ხოლო დანარჩენებს — პატარა ასოდ
text = "hELLO wORLD"
print(text.capitalize())  # შედეგი: "Hello world"


# .find() — ეძებს სტრინგში მითითებულ სიმბოლოს ან სიტყვას
# აბრუნებს პირველივე აღმოჩენილი პოზიციის ინდექსს
# თუ ვერ იპოვა, აბრუნებს -1
text = "python programming"
print(text.find("p"))    # შედეგი: 0
print(text.find("gram")) # შედეგი: 10
print(text.find("java")) # შედეგი: -1


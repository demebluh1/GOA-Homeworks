# მომხმარებელს შემოატანინეთ წინადადება
sentence = input("შეიყვანეთ წინადადება: ")

# მომხმარებელს შემოატანინეთ სიმბოლო
char = input("შეიყვანეთ სიმბოლო: ")

# მთვლელი ცვლადი
count = 0

# ვამოწმებთ თითოეულ სიმბოლოს წინადადებაში
for c in sentence:
    if c == char:
        count += 1

# შედეგის დაბეჭდვა
print("სიმბოლო გვხვდება", count, "ჯერ")


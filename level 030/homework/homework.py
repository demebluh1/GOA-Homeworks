#N3
# მომხმარებელს შემოატანინეთ ელფოსტის მისამართი
email = input("შეიყვანეთ ელფოსტის მისამართი: ")

# .find() აბრუნებს -1 თუ '@' არ მოიძებნა
result = (
    "EMAIL CONTAINS @" * (email.find("@") != -1) +
    "EMAIL DOES NOT CONTAIN @" * (email.find("@") == -1)
)

# შედეგის დაბეჭდვა
print(result)


# N2
# ინდექსი (Index) არის სიის ელემენტების პოზიცია.
# ინდექსი იწყება 0-დან, ანუ პირველი ელემენტი არის ინდექსით 0, მეორე - ინდექსით 1 და ა.შ.
# ინდექსის მაგალითი:
